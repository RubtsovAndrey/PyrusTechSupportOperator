async function createArticles() {
  console.log('🚀 Создание тестовых статей в пространстве "ИИ Техподдержка - Конфигурация"\n');
  
  const createdIds = [];
  
  for (let i = 0; i < articles.length; i++) {
    const article = articles[i];
    console.log(`${i + 1}/${articles.length} Создание: "${article.title}"`);
    
    try {
      // Проверим, не существует ли уже
      const existing = await MCP.searchContent(article.title, [CONFIG_SPACE_ID]);
      
      if (existing.length > 0 && existing[0].articleTitle === article.title) {
        console.log(`   ⚠️  Статья уже существует (ID: ${existing[0].articleId})`);
        console.log(`   ℹ️  Пропускаем создание\n`);
        createdIds.push(existing[0].articleId);
        continue;
      }
      
      const result = await MCP.createContent(
        CONFIG_SPACE_ID,
        article.title,
        article.content,
        article.status
      );
      
      console.log(`   ✅ Создано! ID: ${result.id || result.articleId || 'unknown'}`);
      console.log('');
      
      createdIds.push(result.id || result.articleId);
      
      // Небольшая задержка между запросами
      await new Promise(resolve => setTimeout(resolve, 500));
      
    } catch (error) {
      console.error(`   ❌ Ошибка: ${error.message}\n`);
    }
  }
  
  console.log('✅ Создание завершено!\n');
  console.log('📋 Созданные статьи:');
  articles.forEach((article, i) => {
    console.log(`   ${i + 1}. ${article.title}`);
    if (createdIds[i]) {
      console.log(`      ID: ${createdIds[i]}`);
    }
  });
  
  return createdIds;
}

// Запуск
createArticles()
