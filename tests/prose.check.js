// ── Дерево против прозы: одна и та же статья, одни и те же реплики ──
//
// Запуск: node tests/prose.check.js
//
// Смысл сравнения. Дерево описывает разговор графом: узел спрашивает, ветка выбирается по
// словам партнёра, терминал решает исход. Проза описывает ту же тему текстом, написанным
// как для человека, и разбирается в нём модель. Дерево дороже писать и невозможно
// поддерживать на большом каталоге; проза дешевле, но ничего не гарантирует.
//
// Колонок поэтому три, а не две:
//   дерево          — разговор ведёт граф, модель только распознаёт слова;
//   проза + модель  — модель сделала свою работу: выбрала подходящую часть или спросила;
//   проза + лень    — модель вывалила статью целиком, ничего не выбрав.
//
// Третья колонка не выдумана: ровно так ведёт себя слабая модель, и это тот риск, от
// которого страхует дерево. У дерева такой колонки нет вовсе — там выбор делает код.
//
// ⚠️ Чего этот отчёт НЕ показывает: НАСКОЛЬКО ВЕРОЯТНА вторая колонка против третьей.
// Это свойство конкретной модели, и измеряется оно только живым прогоном.
const { conversation } = require("./dialog");

// Исторический пример намеренно живёт в тестовой фикстуре: эксперимент сравнивает
// два формата статьи и не должен зависеть от состава текущего боевого каталога.
const CATALOG = require("./tree.test.js").dialogCatalog;

// Та же тема, написанная прозой. Ровно то, что первая линия и так пишет в своих
// инструкциях: текст с условиями внутри, без ключей, узлов и синонимов веток.
const PROSE = {
  key: "no_internet",
  description: CATALOG.topics.find(t => t.key === "no_internet").description,
  phrasings: CATALOG.topics.find(t => t.key === "no_internet").phrasings,
  route: "solver",
  onFail: "escalate",
  article: [
    "Сначала нужно понять, пропал ли интернет целиком или не открывается только Додо ИС:",
    "это разные проблемы, и решаются они по-разному.",
    "",
    "Если интернет пропал во всей точке и другие сайты тоже не открываются — связь",
    "обеспечивает провайдер, и восстановить её с нашей стороны нельзя. Попросите",
    "управляющего обратиться к провайдеру и сообщить, что интернета нет во всей точке.",
    "",
    "Если интернет есть, а не открывается только Додо ИС — нужно знать, что именно",
    "происходит при открытии: пустая страница, ошибка или всё сильно тормозит. С этим",
    "разбирается специалист поддержки, сами мы такое не чиним."
  ].join("\n")
};

function catalogWith(topic) {
  return { topics: [JSON.parse(JSON.stringify(topic))] };
}

let taskId = 800000;

async function play(title, catalog, script) {
  const bot = conversation({ taskId: ++taskId, catalog: catalog });
  console.log("\n── " + title);
  for (const step of script) {
    const r = await bot.turn(step[0], step[1]);
    console.log("   партнёр: " + step[0]);
    r.replies.forEach(x => console.log("   бот:     " + String(x).replace(/\n+/g, " / ").slice(0, 150)));
    if (!r.replies.length) console.log("   бот:     (молчит)");
    if (r.internal.length) console.log("   оператору: да");
  }
  const last = bot.turns[bot.turns.length - 1];
  console.log("   ИТОГ: витков " + bot.turns.length + ", финал " + last.stage +
    ", собрано " + JSON.stringify(bot.data.treeAnswers || {}));
  return bot;
}

const TREE = catalogWith(CATALOG.topics.find(t => t.key === "no_internet"));
const AS_PROSE = catalogWith(PROSE);

// Одни и те же реплики партнёра; различаются только подсказки, объявляющие вывод модели.
async function three(title, partner, treeHints, goodHints) {
  console.log("\n════ " + title);
  await play("дерево", TREE, partner.map((p, i) => [p, treeHints[i] || {}]));
  await play("проза + модель сделала работу", AS_PROSE, partner.map((p, i) => [p, goodHints[i] || {}]));
  await play("проза + модель поленилась", AS_PROSE, partner.map((p, i) => [p, i === 0 ? goodHints[0] && { unit: goodHints[0].unit } : {}]));
}

const ISP = "Связь в точке обеспечивает провайдер, восстановить её с нашей стороны нельзя. " +
  "Попросите управляющего обратиться к провайдеру и сообщить, что интернета нет во всей точке.";
const ASK = "Уточните, пожалуйста: интернет пропал целиком и другие сайты тоже не открываются, " +
  "или не работает только Додо ИС?";

async function main() {
  // 1. Партнёр сразу назвал случай. Дереву хватает слов ветки, прозе — вывода модели.
  await three("Партнёр сразу назвал случай: интернета нет целиком",
    ["Тамбов-1, пропал интернет, другие сайты тоже не грузятся"],
    [{ unit: "Тамбов-1" }],
    [{ unit: "Тамбов-1", proseSay: ISP }]);

  // 2. Партнёр описал в общем — нужен уточняющий вопрос, и его источник разный: у дерева
  // это `ask` узла, у прозы — решение модели.
  await three("Партнёр описал в общем: нужен уточняющий вопрос",
    ["Тамбов-1, нет интернета", "другие сайты открываются, только Додо ИС не грузится"],
    [{ unit: "Тамбов-1" }, { answers: { scope: "только Додо ИС" } }],
    [{ unit: "Тамбов-1", proseAsk: ASK }, { proseHandover: true }]);

  // 3. Партнёр отвечает не тем, чего ждали. У дерева на это есть `else` и счётчик неответов;
  // у прозы — только модель, и если она снова не поймёт, спасает общий предохранитель.
  await three("Партнёр отвечает непонятно",
    ["Тамбов-1, нет интернета", "ну как обычно, всё висит"],
    [{ unit: "Тамбов-1" }, {}],
    [{ unit: "Тамбов-1", proseAsk: ASK }, { proseAsk: ASK }]);
}

main().catch(e => { console.error(e); process.exit(1); });
